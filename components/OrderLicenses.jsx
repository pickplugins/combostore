"use client";
import Link from "next/link";
import { useState, useEffect } from "react";
import { IconArrowUpRight, IconCopy, IconKey, IconPlus } from "@tabler/icons-react";

import { useCounterStore } from '../store/useCounterStore'
import Spinner from '../components/Spinner';
import WidgetWrapper from '../components/WidgetWrapper';
import { LICENSE_STATUSES, formatDay, daysFromToday, copyText } from '../components/pages/LicenseEdit';


const serverUrl = process.env.NEXT_PUBLIC_SERVER_URL;

/*
	Licenses tab of OrderEdit.

	Lists the cstore_licenses rows whose order_id is this order (get_licenses
	with an order_id filter), and lets staff issue a license for one of the
	order's line items. The new license takes the order's customer (userid and
	billing email) and the item's product / variation; the key is generated by
	the server.

	Managing a license (status, sites, expiry) happens on its own page: this tab
	can itself be inside the Orders list's drawer, so it links out rather than
	opening a second drawer.
*/

/* Same card shell as OrderSubscription / OrderDelivery. */
const CARD_CLASSES =
	"form-card !gap-0 !rounded-xl border border-gray-200 [&>div:first-child]:!px-5 [&>div:first-child]:!py-4 [&>div:nth-child(2)]:!p-5 [&>div:nth-child(2)]:!pt-3 [&_h2]:text-base [&_h2]:font-semibold [&_h2]:text-gray-900";

const FIELD_CLASSES = "!shadow-none !border !border-gray-300 transition-colors focus:!border-[#634FE5] focus:!ring-2 focus:!ring-[#634FE5]/20 rounded-lg px-3 py-2 text-sm w-full bg-white disabled:bg-gray-50 disabled:text-gray-400";
const ROW_CLASSES = "flex flex-col gap-1.5 border-b border-gray-100 py-3 last:border-0 lg:flex-row lg:items-center lg:gap-4 lg:[&>div+div]:max-w-md lg:[&>div+div]:flex-1";
const ROW_LABEL = "block py-1 text-sm font-medium text-gray-700 lg:w-56 lg:shrink-0";
const PRIMARY_BUTTON = "inline-flex items-center gap-2 rounded-lg bg-[#634FE5] px-4 py-2 text-sm font-semibold text-white shadow-sm transition-colors hover:bg-[#5540d4] cursor-pointer disabled:cursor-not-allowed disabled:opacity-60";
const SECONDARY_BUTTON = "inline-flex items-center gap-1.5 rounded-lg border border-gray-300 bg-white px-3 py-1.5 text-xs font-medium text-gray-700 transition-colors hover:bg-gray-50";

const LIFETIME = "9999-12-31 23:59:59";
const STAFF_ROLES = ["administrator", "store_manager"];


function itemKey(item) {
	return `${parseInt(item?.product_id) || 0}:${parseInt(item?.variation_id) || 0}`;
}

function itemLabel(item) {
	const name = item?.product_name || (item?.product_id ? `Product #${item.product_id}` : "Item");
	return parseInt(item?.quantity) > 1 ? `${name} × ${item.quantity}` : name;
}


const OrderLicenses = (props) => {

	const { token, addNotification, userDataX } = useCounterStore()

	var order_id = props?.order_id

	var [loading, setloading] = useState(false);
	var [creating, setcreating] = useState(false);
	var [order, setorder] = useState(null);
	var [lineItems, setlineItems] = useState([]);
	var [licenses, setlicenses] = useState([]);
	var [form, setform] = useState({ item: "", activation_limit: "1", lifetime: true, expires_at: "" });

	const isStaff = STAFF_ROLES.some(role => userDataX?.roles?.includes(role));


	function post(route, body) {
		return fetch(serverUrl + "wp-json/combo-store/v2/" + route, {
			method: "POST",
			headers: {
				"Content-Type": "application/json",
				Authorization: `Bearer ${token}`,
			},
			body: JSON.stringify(body),
		}).then((response) => {
			if (!response.ok) {
				return response.json().catch(() => ({})).then((res) => {
					throw new Error(res?.message || `Request failed (HTTP ${response.status}).`);
				});
			}
			return response.json();
		});
	}

	function load() {
		if (!order_id || !token) return;

		setloading(true);
		Promise.all([
			post("get_order", { id: order_id }).catch(() => null),
			post("get_licenses", { order_id, per_page: 100 }).catch(() => null),
		]).then(([orderRes, licenseRes]) => {
			setorder(orderRes?.order ?? null);
			setlineItems(orderRes?.line_items ?? []);
			setlicenses(licenseRes?.posts ?? []);
			setloading(false);
		});
	}

	useEffect(() => {
		load();
	}, [order_id, token]);


	/* Line items that have no license yet come first in the picker. */
	const licensedKeys = new Set(licenses.map(itemKey));
	const items = lineItems.filter(item => parseInt(item?.product_id) > 0);
	const unlicensed = items.filter(item => !licensedKeys.has(itemKey(item)));

	useEffect(() => {
		if (!form.item && items.length) {
			setform(f => ({ ...f, item: itemKey(unlicensed[0] ?? items[0]) }));
		}
	}, [lineItems, licenses]);


	function issueLicense() {
		const item = items.find(i => itemKey(i) === form.item);
		if (!item) {
			addNotification({ type: 'error', title: 'Pick an item', content: 'Choose which product the license is for.' });
			return;
		}

		const payload = {
			order_id: parseInt(order_id),
			product_id: parseInt(item.product_id),
			activation_limit: Math.max(0, parseInt(form.activation_limit) || 0),
			expires_at: form.lifetime || !form.expires_at ? LIFETIME : `${form.expires_at} 23:59:59`,
			status: "active",
		};
		if (parseInt(item.variation_id) > 0) payload.variation_id = parseInt(item.variation_id);
		if (parseInt(order?.userid) > 0) payload.userid = parseInt(order.userid);
		if (order?.billing_email) payload.user_email = order.billing_email;

		setcreating(true);
		post("create_license", payload)
			.then((res) => {
				setcreating(false);
				if (res?.status !== "success") throw new Error(res?.message || "Could not create the license.");
				addNotification({ type: 'success', title: 'License issued', content: `License #${res.id} created for ${itemLabel(item)}.` });
				setform(f => ({ ...f, item: "" }));
				load();
			})
			.catch((err) => {
				setcreating(false);
				addNotification({ type: 'error', title: 'License not issued', content: err.message });
			});
	}

	function copyKey(key) {
		copyText(key).then(ok => addNotification(ok
			? { type: 'success', title: 'Copied', content: 'License key copied to clipboard.' }
			: { type: 'error', title: 'Copy failed', content: 'Select the key and copy it manually.' }));
	}


	if (loading && !order && !licenses.length) {
		return (
			<div className="flex items-center gap-2 px-4 py-10 text-sm text-gray-500">
				<Spinner /> {("Loading licenses…")}
			</div>
		);
	}


	return (
		<div className="flex flex-col gap-4">

			{licenses.length === 0 && (
				<div className="flex flex-col items-center gap-3 rounded-xl border border-dashed border-gray-300 bg-white px-6 py-10 text-center">
					<div className="flex h-12 w-12 items-center justify-center rounded-full bg-[#634FE5]/10 text-[#634FE5]">
						<IconKey size={24} />
					</div>
					<div>
						<div className="text-sm font-semibold text-gray-900">{("No licenses for this order")}</div>
						<div className="mt-1 text-xs text-gray-500">
							{isStaff
								? ("Issue a license key for one of the order's products below.")
								: ("License keys for this order will appear here once they are issued.")}
						</div>
					</div>
				</div>
			)}


			{licenses.length > 0 && (
				<div className="overflow-hidden rounded-xl border border-gray-200 bg-white shadow-sm">
					<div className="flex items-center justify-between border-b border-gray-200 px-5 py-3">
						<span className="text-sm font-semibold text-gray-900">{("Licenses")} <span className="font-normal text-gray-400">({licenses.length})</span></span>
						{loading && <Spinner />}
					</div>

					{licenses.map((license) => {
						const status = LICENSE_STATUSES[license.status] ?? { label: license.status || "—", classes: "bg-gray-100 text-gray-600 ring-gray-200" };
						const used = license.domains?.length ?? 0;
						const limit = parseInt(license.activation_limit) || 0;
						const days = daysFromToday(license.expires_at);

						return (
							<div key={license.id} className="flex flex-col gap-3 border-b border-gray-100 px-5 py-4 last:border-0 lg:flex-row lg:items-center lg:justify-between">
								<div className="flex min-w-0 items-start gap-3">
									<div className="flex h-10 w-10 shrink-0 items-center justify-center rounded-lg border border-gray-200 bg-gray-50 text-gray-400">
										<IconKey size={18} stroke={1.5} />
									</div>
									<div className="flex min-w-0 flex-col gap-1">
										<div className="flex flex-wrap items-center gap-2 text-sm">
											<span className="font-medium text-gray-900">#{license.id}</span>
											<span className={`inline-flex items-center rounded-full px-2 py-0.5 text-[11px] font-semibold ring-1 ring-inset ${status.classes}`}>{status.label}</span>
											{license.status === "active" && license.is_expired && <span className="text-[11px] text-red-600">{("Past expiry date")}</span>}
										</div>
										<div className="flex items-center gap-1.5">
											<span className="break-all font-mono text-xs text-gray-700 select-all">{license.license_key}</span>
											<button type="button" className="shrink-0 text-gray-300 transition-colors hover:text-gray-700" title="Copy key" onClick={() => copyKey(license.license_key)}>
												<IconCopy size={14} />
											</button>
										</div>
										<div className="truncate text-xs text-gray-500">
											{license.product_title || (license.product_id ? `Product #${license.product_id}` : "No product")}
											{license.variation_title ? ` · ${license.variation_title}` : ""}
										</div>
									</div>
								</div>

								<div className="flex flex-wrap items-center gap-4 text-xs lg:shrink-0">
									<div className="flex flex-col">
										<span className="text-gray-500">{("Sites")}</span>
										<span className={`tabular-nums font-medium ${limit > 0 && used >= limit ? "text-amber-700" : "text-gray-900"}`}>{used} / {limit > 0 ? limit : "∞"}</span>
									</div>
									<div className="flex flex-col">
										<span className="text-gray-500">{("Expires")}</span>
										<span className={`font-medium ${days !== null && days < 0 ? "text-red-600" : "text-gray-900"}`}>
											{license.is_lifetime ? ("Lifetime") : (formatDay(license.expires_at) ?? "—")}
										</span>
									</div>
									<Link href={`/dashboard/licenses/${license.id}`} className={SECONDARY_BUTTON}>
										{("Manage")} <IconArrowUpRight size={14} />
									</Link>
								</div>
							</div>
						);
					})}
				</div>
			)}


			{isStaff && (
				<WidgetWrapper className={CARD_CLASSES} collapsible={true} title="Issue License">
					<div>
						{items.length === 0 ? (
							<div className="py-3 text-sm text-gray-500">{("This order has no products to license.")}</div>
						) : (
							<>
								<div className={ROW_CLASSES}>
									<label htmlFor="license-item" className={ROW_LABEL}>{("Product")}</label>
									<div>
										<select id="license-item" className={FIELD_CLASSES} value={form.item} onChange={ev => setform({ ...form, item: ev.target.value })}>
											{items.map((item) => (
												<option key={item.id ?? itemKey(item)} value={itemKey(item)}>
													{itemLabel(item)}{licensedKeys.has(itemKey(item)) ? " (already licensed)" : ""}
												</option>
											))}
										</select>
									</div>
								</div>

								<div className={ROW_CLASSES}>
									<label className={ROW_LABEL}>
										{("Customer")}
										<span className="mt-0.5 block text-xs font-normal text-gray-500">{("Taken from the order")}</span>
									</label>
									<div className="text-sm text-gray-700">
										{order?.billing_email || (parseInt(order?.userid) > 0 ? `User #${order.userid}` : <span className="text-amber-600">{("No customer or email on this order")}</span>)}
									</div>
								</div>

								<div className={ROW_CLASSES}>
									<label htmlFor="license-limit" className={ROW_LABEL}>
										{("Activation Limit")}
										<span className="mt-0.5 block text-xs font-normal text-gray-500">{("0 means unlimited sites")}</span>
									</label>
									<div>
										<input id="license-limit" type="number" min="0" step="1" className={FIELD_CLASSES} value={form.activation_limit} onChange={ev => setform({ ...form, activation_limit: ev.target.value })} />
									</div>
								</div>

								<div className={ROW_CLASSES}>
									<label htmlFor="license-expires" className={ROW_LABEL}>{("Expires")}</label>
									<div className="flex flex-col gap-2">
										<label className="flex items-center gap-2 text-sm text-gray-700">
											<input type="checkbox" className="h-4 w-4 accent-[#634FE5]" checked={form.lifetime} onChange={ev => setform({ ...form, lifetime: ev.target.checked })} />
											{("Lifetime (never expires)")}
										</label>
										<input id="license-expires" type="date" className={FIELD_CLASSES} disabled={form.lifetime} value={form.expires_at} onChange={ev => setform({ ...form, expires_at: ev.target.value })} />
									</div>
								</div>

								<div className="pt-3">
									<button type="button" className={PRIMARY_BUTTON} disabled={creating || !form.item || (!form.lifetime && !form.expires_at)} onClick={issueLicense}>
										{creating ? <Spinner /> : <IconPlus size={16} />}
										{("Issue License")}
									</button>
								</div>
							</>
						)}
					</div>
				</WidgetWrapper>
			)}

		</div>
	);
};

export default OrderLicenses;
