import tablerIcons from './tabler-icons.json';

/*
	Server side of the storefront's icons (components/icons/TablerIcon.jsx).
	tabler-icons.json is generated by scripts/build-tabler-icons.mjs; it stays
	on the server, and pages receive only the icons they draw.
*/

/* What an icon name looks like: a Tabler export name. */
export const ICON_NAME = /^Icon[A-Za-z0-9]+$/;

/* An icon's data [type, kebab name, node], or null for a name Tabler does not have. */
export function iconData(name) {
	var entry = tablerIcons[name];
	if (typeof entry === 'string') entry = tablerIcons[entry];
	return Array.isArray(entry) ? entry : null;
}

/* { name: data | null } for the names. */
export function iconsData(names) {
	var out = {};
	for (const name of names) if (ICON_NAME.test(name)) out[name] = iconData(name);
	return out;
}

/*
	Every icon name in a page's blocks: any string value anywhere in them that
	looks like one (options.icon, items[].icon, prevIcon, labelIcon, ...), so
	a new icon option needs no change here. Capped, in case of odd content.
*/
export function collectIconNames(blocks, limit = 400) {
	var names = new Set();
	var seen = new Set();
	var walk = (value) => {
		if (names.size >= limit) return;
		if (typeof value === 'string') { if (ICON_NAME.test(value)) names.add(value); return; }
		if (!value || typeof value !== 'object' || seen.has(value)) return;
		seen.add(value);
		for (const v of Array.isArray(value) ? value : Object.values(value)) walk(v);
	};
	walk(blocks);
	return [...names];
}
